#!/usr/bin/env bash
# Generate development and local-production environment files for VaultStack.
# Safe to re-run: preserves existing secrets unless FORCE_REGENERATE=true.
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

force="${FORCE_REGENERATE:-false}"
dev_api_port="${DEV_API_PORT:-5000}"
dev_env="${ROOT_DIR}/.env"
compose_env="${ROOT_DIR}/infrastructure/docker/compose.env"
secret_dir="${ROOT_DIR}/infrastructure/docker/secrets"

rand_hex() {
  openssl rand -hex "$1"
}

read_or_generate() {
  local file="$1"
  local bytes="$2"
  if [[ "${force}" == "true" ]] || [[ ! -s "${file}" ]]; then
    rand_hex "${bytes}"
  else
    cat "${file}"
  fi
}

install -d -m 0700 "${secret_dir}"
install -d -m 0750 "${ROOT_DIR}/.vaultstack/storage"
install -d -m 0750 "${ROOT_DIR}/.vaultstack/backups"

postgres_password="$(read_or_generate "${secret_dir}/postgres_password" 24)"
jwt_secret="$(read_or_generate "${secret_dir}/jwt_secret" 32)"
metrics_token="$(read_or_generate "${secret_dir}/metrics_token" 32)"
grafana_admin_password="$(read_or_generate "${secret_dir}/grafana_admin_password" 24)"

umask 077
printf '%s\n' "${postgres_password}" > "${secret_dir}/postgres_password"
printf '%s\n' "${jwt_secret}" > "${secret_dir}/jwt_secret"
printf '%s\n' "${metrics_token}" > "${secret_dir}/metrics_token"
printf '%s\n' "${grafana_admin_password}" > "${secret_dir}/grafana_admin_password"
printf 'postgresql://vaultstack:%s@postgres:5432/vaultstack\n' "${postgres_password}" \
  > "${secret_dir}/database_url"
chmod 0600 "${secret_dir}/"*

minio_password="vaultstack_minio_dev_password"

cat > "${dev_env}" <<EOF
# VaultStack — local development (generated by scripts/init-env.sh)
# Re-run with FORCE_REGENERATE=true to rotate JWT/metrics secrets.

# ---------------------------------------------------------------------------
# API
# ---------------------------------------------------------------------------
NODE_ENV=development
API_HOST=0.0.0.0
API_PORT=${dev_api_port}
LOG_LEVEL=info

# ---------------------------------------------------------------------------
# Database & queues
# ---------------------------------------------------------------------------
DATABASE_URL=postgresql://vaultstack:vaultstack_dev@localhost:5432/vaultstack
REDIS_URL=redis://localhost:6379

# ---------------------------------------------------------------------------
# Auth & security (server-side only — never expose to the browser)
# ---------------------------------------------------------------------------
JWT_SECRET=${jwt_secret}
SESSION_TTL_SECONDS=43200
LOGIN_RATE_LIMIT_MAX=5
LOGIN_RATE_LIMIT_WINDOW_SECONDS=900
API_RATE_LIMIT_MAX=300
API_RATE_LIMIT_WINDOW_SECONDS=60
CORS_ORIGINS=http://localhost:5173,http://127.0.0.1:5173

# ---------------------------------------------------------------------------
# Storage (local filesystem is the primary backend)
# ---------------------------------------------------------------------------
STORAGE_DRIVER=local
STORAGE_LOCAL_ROOT=./.vaultstack/storage
STORAGE_MAX_OBJECT_SIZE_BYTES=5368709120
STORAGE_MAX_REQUEST_SIZE_BYTES=67108864
STORAGE_MULTIPART_MIN_PART_SIZE_BYTES=5242880
STORAGE_MULTIPART_MAX_PARTS=10000
STORAGE_MAX_METADATA_BYTES=2048
STORAGE_MAX_KEY_LENGTH=1024
STORAGE_PRESIGNED_URL_TTL_SECONDS=900
STORAGE_UPLOAD_TTL_SECONDS=3600

# ---------------------------------------------------------------------------
# S3-compatible gateway (dev: enabled against local API)
# ---------------------------------------------------------------------------
S3_GATEWAY_ENABLED=true
S3_GATEWAY_REGION=vaultstack
S3_ALLOW_PRIVATE_ENDPOINTS=true

# Optional external S3/MinIO provider (uncomment after: pnpm docker:up --profile minio)
# S3_ENDPOINT=http://localhost:9000
# S3_REGION=us-east-1
# S3_ACCESS_KEY=vaultstack_minio
# S3_SECRET_KEY=${minio_password}
# S3_FORCE_PATH_STYLE=true

# ---------------------------------------------------------------------------
# MinIO (optional — docker compose --profile minio)
# ---------------------------------------------------------------------------
MINIO_ROOT_USER=vaultstack_minio
MINIO_ROOT_PASSWORD=${minio_password}
MINIO_ENDPOINT=localhost
MINIO_PORT=9000
MINIO_USE_SSL=false
MINIO_ACCESS_KEY=vaultstack_minio
MINIO_SECRET_KEY=${minio_password}
MINIO_BUCKET=vaultstack

# ---------------------------------------------------------------------------
# Backups
# ---------------------------------------------------------------------------
BACKUP_TEMP_DIR=./.vaultstack/backups
BACKUP_MAX_CONCURRENT_JOBS=1
BACKUP_PROCESS_INLINE=false

# ---------------------------------------------------------------------------
# Infrastructure monitoring (Phase 13) + metrics (Phase 19)
# ---------------------------------------------------------------------------
DOCKER_SOCKET=/var/run/docker.sock
INFRASTRUCTURE_DISK_PATHS=./.vaultstack/storage
METRICS_TOKEN=${metrics_token}

# ---------------------------------------------------------------------------
# Dashboard (Vite — loaded from this file via apps/dashboard/vite.config.ts)
# ---------------------------------------------------------------------------
VITE_API_URL=http://localhost:${dev_api_port}
EOF

chmod 0600 "${dev_env}"

# Local bind mount for production Compose smoke tests on a dev machine.
local_data_root="${ROOT_DIR}/.vaultstack/data"
install -d -m 0750 "${local_data_root}"

cat > "${compose_env}" <<EOF
# VaultStack production Compose — local smoke-test paths (generated by scripts/init-env.sh)
# For Ubuntu deployment, copy infrastructure/deployment/ubuntu/compose.env.example
# to /srv/vaultstack/config/compose.env instead.

COMPOSE_PROJECT_NAME=vaultstack

VAULTSTACK_BUILD_CONTEXT=${ROOT_DIR}
VAULTSTACK_MONITORING_CONFIG_DIR=${ROOT_DIR}/infrastructure/monitoring
VAULTSTACK_DATA_ROOT=${local_data_root}

DASHBOARD_DOMAIN=vault.localhost
API_DOMAIN=api.vault.localhost
S3_DOMAIN=s3.vault.localhost
VITE_API_URL=http://api.vault.localhost
CORS_ORIGINS=http://vault.localhost
S3_ALLOW_PRIVATE_ENDPOINTS=false
S3_GATEWAY_ENABLED=true

VAULTSTACK_DATABASE_URL_FILE=${secret_dir}/database_url
VAULTSTACK_JWT_SECRET_FILE=${secret_dir}/jwt_secret
VAULTSTACK_POSTGRES_PASSWORD_FILE=${secret_dir}/postgres_password
VAULTSTACK_METRICS_TOKEN_FILE=${secret_dir}/metrics_token
VAULTSTACK_GRAFANA_ADMIN_PASSWORD_FILE=${secret_dir}/grafana_admin_password

POSTGRES_USER=vaultstack
POSTGRES_DB=vaultstack
GRAFANA_ADMIN_USER=admin
LOG_LEVEL=info
EOF

chmod 0600 "${compose_env}"

echo "Wrote ${dev_env}"
echo "Wrote ${compose_env}"
echo "Wrote Docker secrets in ${secret_dir}/"
echo ""
echo "Development:"
echo "  pnpm docker:up && pnpm db:migrate && pnpm db:seed"
echo "  pnpm build && pnpm dev"
echo ""
echo "Local production Compose (requires /etc/hosts entries for *.vault.localhost):"
echo "  docker compose --env-file infrastructure/docker/compose.env \\"
echo "    -f infrastructure/docker/docker-compose.prod.yml up -d --build"
